export const guessLang = (): Lang => (navigator.language?.toLowerCase().startsWith('ja') ? 'ja' : 'es');

const WEEKDAYS: Record<Lang, string[]> = {
  es: ['domingo', 'lunes', 'martes', 'miércoles', 'jueves', 'viernes', 'sábado'],
  ja: ['日', '月', '火', '水', '木', '金', '土'],
};
const MONTHS_ES = ['ene', 'feb', 'mar', 'abr', 'may', 'jun', 'jul', 'ago', 'sept', 'oct', 'nov', 'dic'];

/** Fecha de cabecera en JST, sin toLocaleDateString (ver CLAUDE.md). */
export function headerDate(lang: Lang, now: Date): string {
  const j = new Date(now.getTime() + 9 * 3_600_000);
  const wd = WEEKDAYS[lang][j.getUTCDay()];
  const d = j.getUTCDate();
  const m = j.getUTCMonth();
  if (lang === 'ja') return `${m + 1}月${d}日（${wd}）`;
  return `${wd[0].toUpperCase()}${wd.slice(1)}, ${d} ${MONTHS_ES[m]}`;
}

